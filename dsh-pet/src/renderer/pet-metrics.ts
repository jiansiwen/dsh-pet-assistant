/**
 * 角色的几何常量。
 *
 * 单独成文件而不是留在 `usePetBehavior.ts`，是因为布局算法（`stage-layout.ts`）也要用它们，
 * 而 Node 的类型剥离能跑纯 `.ts` 却跑不动 `.tsx`、也不会把 `./x.js` 重写成 `./x.ts`。
 * 布局层若从行为引擎导入，测试就得连带把 React 拖进来；这里只有两个数字，谁都依赖得起。
 */

/** 角色精灵的边长。命中盒、座位间距、面板锚点都基于它。 */
export const PET_WIDTH = 150

/**
 * 角色围绕"家"徘徊的半径。
 *
 * 座位排布并不直接用它算间距（那用的是 `PET_WIDTH + 24`）；它是判断"两个角色的徘徊圈
 * 会不会相交"的阈值：间距要达到 `PET_WIDTH + 2 * WANDER_RADIUS` = 330px 才完全不相交，
 * 五个角色就需要 1650px 可用宽度。1920 的屏够，1280 不够 —— 那时接受走动时擦肩而过，
 * 只保证静态不重叠。`tests/stage.test.ts` 里把这条取舍钉住了。
 */
export const WANDER_RADIUS = 90

/**
 * 舞台四周的边距：角色最左、最右、最上、最下能待到的位置都由它决定。
 *
 * 座位排布、越界夹取、拖拽限位、默认落点必须共用这一个值。此前排布用 6、夹取用 8，
 * 结果是刚排好的座位再夹取一次会被挪走 2px，而默认落点比拖拽能到达的最底位置还低 ——
 * 用户把角色拖到底、重启后它会自己往上跳一点。
 */
export const STAGE_MARGIN = 8
